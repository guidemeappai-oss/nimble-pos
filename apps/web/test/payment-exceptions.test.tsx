import {act,cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {afterEach,expect,it,vi} from 'vitest'
import {PaymentExceptions} from '../src/merchant/PaymentExceptions'
import {MerchantApi} from '../src/merchant/client'
afterEach(()=>{cleanup();vi.restoreAllMocks();sessionStorage.clear()})
const row={order:{id:'order-a',number:12,status:'AWAITING_PAYMENT',source:'REMOTE',totalMinor:500,createdAt:'2026-10-15T00:00:00Z',decisionAt:null,delayMinutes:0,requiresRefund:false},kind:'UNVERIFIED',attempts:[{id:'attempt-a',purpose:'PAYMENT',hash:'0xabc',asset:'USDT',amountAtomic:'1000000',createdAt:'2026-10-15T00:00:00Z',checks:1,nextCheckAt:null,verification:'UNVERIFIED'}],holds:[{itemId:'coffee',quantity:2}],quoteExpiresAt:null,lastRecheckAt:null}
const response={updatedAt:'2026-10-16T10:00:00Z',items:[row],hasMore:true}
it('requires an explicit rejection reason and retries an uncertain decision with the same intent',async()=>{
 const api=new MerchantApi('',()=>'',()=>'',()=>null)
 const request=vi.spyOn(api,'request').mockImplementation(async(_authority,method)=>{if(method==='GET')return response;throw new Error('offline')})
 render(<PaymentExceptions api={api} venueId="a" scope="owner:a" onRefunds={()=>{}}/>)
 await screen.findByText('0xabc')
 expect(screen.getByText(/A submitted hash is not proof/)).toBeTruthy()
 const reject=screen.getByRole('button',{name:'Reject fulfillment and release stock'}) as HTMLButtonElement
 expect(reject.disabled).toBe(true)
 fireEvent.change(screen.getByLabelText('Reason for rejecting fulfillment'),{target:{value:'Kitchen closed'}})
 fireEvent.click(reject)
 await screen.findByRole('alert')
 fireEvent.click(screen.getByRole('button',{name:'Retry the same decision'}))
 await waitFor(()=>expect(request.mock.calls.filter(call=>call[1]==='POST')).toHaveLength(2))
 const posts=request.mock.calls.filter(call=>call[1]==='POST')
 expect(posts[0][3]).toEqual(posts[1][3])
 expect((posts[0][3] as {reason:string}).reason).toBe('Kitchen closed')
})
it('resets pagination when filters change and ignores an old page response',async()=>{
 const api=new MerchantApi('',()=>'',()=>'',()=>null)
 let old!:(value:unknown)=>void
 const request=vi.spyOn(api,'request').mockResolvedValueOnce(response).mockImplementationOnce(()=>new Promise(resolve=>{old=resolve})).mockResolvedValue({...response,items:[],hasMore:false})
 render(<PaymentExceptions api={api} venueId="a" scope="owner:a" onRefunds={()=>{}}/>)
 await screen.findByText('0xabc')
 fireEvent.click(screen.getByRole('button',{name:'Next page'}))
 fireEvent.change(screen.getByLabelText('Asset filter'),{target:{value:'NIM'}})
 await screen.findByText('No matching payment exceptions.')
 await act(async()=>old(response))
 expect(screen.queryByText('0xabc')).toBeNull()
 expect(request.mock.calls.at(-1)?.[2]).toContain('page=0')
 expect(request.mock.calls.at(-1)?.[2]).toContain('asset=NIM')
})
it('keeps a rejection outcome separate from payment confirmation',async()=>{
 sessionStorage.clear()
 const api=new MerchantApi('',()=>'',()=>'',()=>null)
 vi.spyOn(api,'request').mockImplementation(async(_authority,method)=>method==='GET'?response:{operationId:'operation-a',state:'COMPLETE',orderId:'order-a',orderStatus:'AWAITING_PAYMENT',requiresRefund:false,outcome:'REJECTED'})
 render(<PaymentExceptions api={api} venueId="a" scope="owner:a" onRefunds={()=>{}}/>)
 await screen.findByText('0xabc')
 fireEvent.change(screen.getByLabelText('Reason for rejecting fulfillment'),{target:{value:'Kitchen closed'}})
 fireEvent.click(screen.getByRole('button',{name:'Reject fulfillment and release stock'}))
 await screen.findByText('Fulfillment rejected. Stock released; payment monitoring continues.')
 expect(screen.getByText('UNVERIFIED')).toBeTruthy()
 expect(screen.queryByText('The server verified the transfer.')).toBeNull()
})
it('does not expose an old venue after switching owner scope',async()=>{
 sessionStorage.clear()
 const api=new MerchantApi('',()=>'',()=>'',()=>null)
 let old!:(value:unknown)=>void
 vi.spyOn(api,'request').mockImplementationOnce(()=>new Promise(resolve=>{old=resolve})).mockResolvedValue({...response,items:[],hasMore:false})
 const view=render(<PaymentExceptions api={api} venueId="a" scope="owner:a" onRefunds={()=>{}}/>)
 view.rerender(<PaymentExceptions api={api} venueId="b" scope="owner:b" onRefunds={()=>{}}/>)
 await screen.findByText('No matching payment exceptions.')
 await act(async()=>old(response))
 expect(screen.queryByText('0xabc')).toBeNull()
})
it('preserves an uncertain decision across reopening the payments section',async()=>{
 const api=new MerchantApi('',()=>'',()=>'',()=>null)
 const request=vi.spyOn(api,'request').mockImplementation(async(_authority,method)=>{if(method==='GET')return response;throw new Error('offline')})
 const view=render(<PaymentExceptions api={api} venueId="a" scope="owner:a" onRefunds={()=>{}}/>)
 await screen.findByText('0xabc')
 fireEvent.click(screen.getByRole('button',{name:'Recheck payment'}))
 await screen.findByRole('alert')
 view.unmount()
 render(<PaymentExceptions api={api} venueId="a" scope="owner:a" onRefunds={()=>{}}/>)
 fireEvent.click(await screen.findByRole('button',{name:'Retry the same decision'}))
 await waitFor(()=>expect(request.mock.calls.filter(call=>call[1]==='POST')).toHaveLength(2))
 const posts=request.mock.calls.filter(call=>call[1]==='POST')
 expect(posts[1][3]).toEqual(posts[0][3])
})
it('allows rechecking an unverified payment after fulfillment rejection without offering a premature refund',async()=>{
 const api=new MerchantApi('',()=>'',()=>'',()=>null)
 vi.spyOn(api,'request').mockResolvedValue({...response,items:[{...row,contextTruncated:true,order:{...row.order,requiresRefund:true,fulfillmentRejectedAt:'2026-10-16T09:00:00Z'}}]})
 render(<PaymentExceptions api={api} venueId="a" scope="owner:a" onRefunds={()=>{}}/>)
 await screen.findByText('0xabc')
 expect(screen.getByRole('button',{name:'Recheck payment'})).toBeTruthy()
 expect(screen.queryByRole('button',{name:'Open owner refund approvals'})).toBeNull()
 expect((screen.getByRole('button',{name:'Reject fulfillment and release stock'}) as HTMLButtonElement).disabled).toBe(true)
 expect(screen.getByText('Payment context is limited to the first 25 attempts and held resources.')).toBeTruthy()
})
