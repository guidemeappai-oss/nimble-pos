import {act,cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {afterEach,expect,it,vi} from 'vitest'
import {InventoryBarcodeScanner} from '../src/merchant/InventoryBarcodeScanner'
const originalMedia=Object.getOwnPropertyDescriptor(navigator,'mediaDevices')
afterEach(()=>{cleanup();vi.useRealTimers();vi.restoreAllMocks();vi.unstubAllGlobals();if(originalMedia)Object.defineProperty(navigator,'mediaDevices',originalMedia);else Reflect.deleteProperty(navigator,'mediaDevices')})
it('offers manual entry when barcode detection is unavailable',async()=>{
 vi.stubGlobal('BarcodeDetector',undefined)
 const read=vi.fn()
 render(<InventoryBarcodeScanner onRead={read}/>)
 fireEvent.click(screen.getByRole('button',{name:'Scan stock barcode'}))
 expect((await screen.findByRole('alert')).textContent).toMatch(/Enter the barcode manually/)
 expect(read).not.toHaveBeenCalled()
 expect((screen.getByRole('button',{name:'Scan stock barcode'}) as HTMLButtonElement).disabled).toBe(false)
})
it('releases a camera that becomes available after the scanner has unmounted',async()=>{
 let finish!:(stream:MediaStream)=>void
 const stop=vi.fn(),read=vi.fn(),camera=vi.fn(()=>new Promise<MediaStream>(resolve=>{finish=resolve}))
 vi.stubGlobal('BarcodeDetector',class {static async getSupportedFormats(){return ['ean_13']} async detect(){return []}})
 Object.defineProperty(navigator,'mediaDevices',{configurable:true,value:{getUserMedia:camera}})
 const view=render(<InventoryBarcodeScanner onRead={read}/>)
 fireEvent.click(screen.getByRole('button',{name:'Scan stock barcode'}))
 await waitFor(()=>expect(camera).toHaveBeenCalled())
 view.unmount()
 await act(async()=>finish({getTracks:()=>[{stop}]} as unknown as MediaStream))
 expect(stop).toHaveBeenCalledTimes(1)
 expect(read).not.toHaveBeenCalled()
})
it('reads one barcode and stops the video stream',async()=>{
 vi.useFakeTimers()
 const stop=vi.fn(),read=vi.fn()
 vi.spyOn(HTMLMediaElement.prototype,'srcObject','set').mockImplementation(()=>{})
 vi.spyOn(HTMLMediaElement.prototype,'play').mockResolvedValue()
 vi.spyOn(HTMLMediaElement.prototype,'readyState','get').mockReturnValue(4)
 vi.stubGlobal('BarcodeDetector',class {static async getSupportedFormats(){return ['ean_13']} async detect(){return [{rawValue:'5901234123457'}]}})
 Object.defineProperty(navigator,'mediaDevices',{configurable:true,value:{getUserMedia:vi.fn(async()=>({getTracks:()=>[{stop}]}))}})
 render(<InventoryBarcodeScanner onRead={read}/>)
 fireEvent.click(screen.getByRole('button',{name:'Scan stock barcode'}))
 await act(async()=>{await vi.advanceTimersByTimeAsync(0)})
 expect(screen.queryByRole('alert')).toBeNull()
 expect(screen.getByRole('button',{name:'Stop camera'})).toBeTruthy()
 const video=screen.getByLabelText('Stock barcode camera')
 Object.defineProperty(video,'readyState',{configurable:true,value:4})
 await act(async()=>{await vi.advanceTimersByTimeAsync(1000)})
 expect(read).toHaveBeenCalledTimes(1)
 expect(read).toHaveBeenCalledWith('5901234123457')
 expect(stop).toHaveBeenCalledTimes(1)
})
