import { afterAll, expect, it } from "vitest";
import { freshDb } from "./helpers/db";
import { authedApp, makeUser } from "./helpers/actors";
const { db, close } = await freshDb();
const { app, tokenFor } = authedApp(db);
afterAll(async () => {
    await app.close();
    await close();
});
async function setup() {
    const headers = { authorization: `Bearer ${await tokenFor(await makeUser(db, "NQ-stock-" + crypto.randomUUID()))}` };
    const venue = (await app.inject({ method: "POST", url: "/v1/merchant/venues", headers, payload: { name: "Stock", fiatCurrency: "EUR", nimAddress: "NQ-stock-owner-123" } })).json();
    return { headers, base: `/v1/merchant/venues/${venue.id}/inventory` };
}
it("persists stock movements and reverses a mistake exactly once", async () => {
    const { headers, base } = await setup();
    const created = await app.inject({ method: "POST", url: base, headers, payload: { name: "Croissant", unit: "PIECE", tracked: true, openingQuantity: 24, threshold: 3, reason: "Opening count", idempotencyKey: crypto.randomUUID() } });
    expect(created.statusCode).toBe(201);
    const item = created.json();
    const openingPayload = {name:"Croissant",unit:"PIECE",tracked:true,openingQuantity:24,threshold:3,reason:"Opening count",idempotencyKey:crypto.randomUUID()};
    const firstCreate = await app.inject({method:"POST",url:base,headers,payload:openingPayload});
    expect((await app.inject({method:"POST",url:base,headers,payload:openingPayload})).json()).toEqual(firstCreate.json());
    expect((await app.inject({method:"POST",url:base,headers,payload:{...openingPayload,openingQuantity:25}})).statusCode).toBe(409);
    const adjust = (delta: number, revision: number, idempotencyKey = crypto.randomUUID()) => app.inject({ method: "POST", url: `${base}/${item.id}/movements`, headers, payload: { delta, revision, idempotencyKey, reason: "Count correction" } });
    const key = crypto.randomUUID(), minus = await adjust(-3, 1, key);
    expect(minus.json().item.quantity).toBe(21);
    expect((await adjust(-3, 1, key)).json()).toEqual(minus.json());
    expect((await adjust(-2, 1, key)).statusCode).toBe(409);
    expect((await adjust(10, 2)).json().item.quantity).toBe(31);
    const url = `${base}/${item.id}/movements/${minus.json().movement.id}/reverse`, payload = { revision: 3, reason: "Correct mistake", idempotencyKey: crypto.randomUUID() };
    const reversed = await app.inject({ method: "POST", url, headers, payload });
    expect(reversed.json().item.quantity).toBe(34);
    expect((await app.inject({ method: "POST", url, headers, payload })).json()).toEqual(reversed.json());
    expect((await app.inject({ method: "POST", url, headers, payload: { ...payload, revision: 4, idempotencyKey: crypto.randomUUID() } })).statusCode).toBe(409);
    const history=(await app.inject({ url: `${base}/${item.id}/movements`, headers })).json().movements;
    expect(history.map((m:any)=>m.delta)).toEqual([24,-3,10,3]);
    expect(history[1]).toMatchObject({reason:"Count correction",actorKind:"owner",reversedByMovementId:reversed.json().movement.id});
    expect(history[3].reversesMovementId).toBe(history[1].id);
});
it("enforces revisions, nonnegative stock, bounded history and isolated venues", async () => {
    const { headers, base } = await setup();
    const create = async (name: string, openingQuantity = 2) => (await app.inject({ method: "POST", url: base, headers, payload: { name, unit: "PORTION", tracked: true, openingQuantity, threshold: 1, reason: "Opening", idempotencyKey: crypto.randomUUID() } })).json();
    const item = await create("Soup");
    await create("Cake");
    const list = (await app.inject({ url: base + "?page=0&limit=1", headers })).json();
    expect(list.items).toHaveLength(1);
    expect(list.hasMore).toBe(true);
    expect((await app.inject({ url: base + "?page=1&limit=1", headers })).json().items[0].id).not.toBe(list.items[0].id);
    const move = (delta: number, revision = 1, reason = "Correction") => app.inject({ method: "POST", url: `${base}/${item.id}/movements`, headers, payload: { delta, revision, reason, idempotencyKey: crypto.randomUUID() } });
    expect((await move(-3)).statusCode).toBe(409);
    expect((await move(1, 1, " ")).statusCode).toBe(400);
    const results = await Promise.all([move(-2), move(-2)]);
    expect(results.map(r => r.statusCode).sort()).toEqual([200, 409]);
    expect((await app.inject({ url: base, headers })).json().items.find((x: any) => x.id === item.id).quantity).toBe(0);
    const opening = (await app.inject({ url: `${base}/${item.id}/movements?limit=1`, headers })).json();
    expect(opening.hasMore).toBe(true);
    expect((await app.inject({ method: "POST", url: `${base}/${item.id}/movements/${opening.movements[0].id}/reverse`, headers, payload: { revision: 2, reason: "Reverse opening", idempotencyKey: crypto.randomUUID() } })).statusCode).toBe(409);
    const other = await setup();
    expect((await app.inject({ url: `${other.base}/${item.id}/movements`, headers: other.headers })).statusCode).toBe(404);
    const full = await create("Bound", 2147483647);
    expect((await app.inject({ method: "POST", url: `${base}/${full.id}/movements`, headers, payload: { delta: 1, revision: 1, reason: "Overflow", idempotencyKey: crypto.randomUUID() } })).statusCode).toBe(409);
    const patched = await app.inject({ method: "PATCH", url: `${base}/${item.id}`, headers, payload: { name: "Soup renamed", threshold: 4, tracked: false, revision: 2, reason: "Pause tracking" } });
    expect(patched.json()).toMatchObject({ name: "Soup renamed", tracked: false, quantity: 0, revision: 3 });
    expect((await app.inject({ url: `${base}/${item.id}/movements`, headers })).json().movements).toHaveLength(2);
    expect((await app.inject({ method: "DELETE", url: `${base}/${item.id}/movements/${opening.movements[0].id}`, headers })).statusCode).toBe(404);
});
it("checks live inventory permissions and keeps stock readable by ordinary cashiers", async () => {
    const { headers, base } = await setup(), venueBase = base.replace("/inventory", "");
    const employee = (await app.inject({ method: "POST", url: venueBase + "/employees", headers, payload: { name: "Worker", pin: "1234" } })).json();
    const terminal = (await app.inject({ method: "POST", url: venueBase + "/terminal", headers })).json();
    const token = (await app.inject({ method: "POST", url: "/v1/merchant/terminal/login", headers: { "x-terminal-token": terminal.terminalToken }, payload: { employeeId: employee.id, pin: "1234" } })).json().token;
    const worker = { authorization: `Bearer ${token}` };
    const payload = { name: "Cake", unit: "PIECE", tracked: true, openingQuantity: 5, threshold: 1, reason: "Opening", idempotencyKey: crypto.randomUUID() };
    expect((await app.inject({ url: base, headers: worker })).statusCode).toBe(200);
    expect((await app.inject({ method: "POST", url: base, headers: worker, payload })).statusCode).toBe(403);
    await app.inject({ method: "PATCH", url: `/v1/merchant/employees/${employee.id}`, headers, payload: { role: "MANAGER", permissions: ["inventory.manage"], reason: "Manage stock" } });
    const created = await app.inject({ method: "POST", url: base, headers: worker, payload });
    expect(created.statusCode).toBe(201);
    await app.inject({ method: "PATCH", url: `/v1/merchant/employees/${employee.id}`, headers, payload: { role: "MANAGER", permissions: [], reason: "Revoke stock" } });
    expect((await app.inject({ method: "POST", url: base, headers: worker, payload })).statusCode).toBe(403);
    expect((await app.inject({ url: `${base}/${created.json().id}/movements`, headers: worker })).statusCode).toBe(200);
});
